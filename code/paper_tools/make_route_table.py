"""tables/tab_routes.tex: compact summary of where wait comes from, by training route (replaces the hero strip and the
per-model figure in the main text). Numbers from numbers/results.tex only (route_keys.json, zerorl_keys.json)."""
import re
from pathlib import Path
K = dict(re.findall(r"\\resdef\{([^}]*)\}\{(.*?)\}[ \t]*(?:%.*)?$", Path("numbers/results.tex").read_text(), re.M))
ROWS = [("Zero-RL from a base without it", "h1.zr.n_runs", "h1.zr.n_counter", "h1.zr.final_median", True),
        ("Fine-tuned on traces, base without it", "h1.route.sftfree.n", "h1.route.sftfree.n_ge05", "h1.route.sftfree.median", False),
        ("Post-trained on a base that writes it", "h1.route.postmarked.n", "h1.route.postmarked.n_ge05", "h1.route.postmarked.median", False),
        ("RL on a model that writes it", "h1.route.rlmarked.n", "h1.route.rlmarked.n_ge05", "h1.route.rlmarked.median", False),
        ("Base not released", "h1.route.nobase.n", "h1.route.nobase.n_ge05", "h1.route.nobase.median", False)]
L = [r"% AUTO-GENERATED by tools/make_route_table.py -- do not edit by hand.", r"\begin{table}[t]", r"  \centering\tabstyle\footnotesize",
     r"  \caption{\textbf{Zero-RL rarely yields \form{wait}; every other route to it passes through training data.} Models that write it after training ($\ge$0.05 per 1k tokens); cell shading grows with the share (white 0\%, dark 100\%).}",
     r"  \label{tab:routes}", r"  \fitwidth{\begin{tabular}{@{}lccc@{}}", r"    \toprule",
     r"    \textbf{Training route} & \textbf{Write it} & \textbf{Share (\%)} & \textbf{Median per 1k} \\", r"    \midrule"]
for name, kn, kk, km, ours in ROWS:
    n, k = int(K[kn].replace("{,}", "")), int(K[kk].replace("{,}", ""))
    sh = round(100 * k / n)
    share = rf"\cellcolor{{gray!{round(0.45 * sh)}}}{sh}"
    L.append(f"    {name} & \\res{{{kk}}} of \\res{{{kn}}} & {share} & \\res{{{km}}} \\\\")
L += [r"    \bottomrule", r"  \end{tabular}}", r"\end{table}"]
Path("tables/tab_routes.tex").write_text("\n".join(L) + "\n")
print("tab_routes written")
