"""Calibrated Wait tables from numbers/results.tex (keys h5.*): tables/tab_cw_abl_dev.tex (DEV ablations, sec:cw:abl).
Rows appear only for models whose keys exist, so the table has no empty cells."""
import re
from pathlib import Path

K = dict(re.findall(r"\\resdef\{([^}]*)\}\{(.*?)\}[ \t]*(?:%.*)?$", Path("numbers/results.tex").read_text(), re.M))
def num(k):
    return float(K[k].replace(r"\ensuremath{-}", "-").replace("{,}", ""))
MODELS = [("rlzero", "OLMo-3-7B RL-Zero-Math"), ("olmo3think", "OLMo-3-7B-Think"),
          ("r1d7", "R1-Distill-Qwen-7B"), ("qwen3_8b", "Qwen3-8B")]
ARMS = [("cw_off", r"CW (entropy, all of $F$)"), ("lp", "log-prob.\\ feature"), ("waitonly", r"\form{wait} forms only")]
FIELDS = ["tau", "rho.lo", "hr.vanilla", "hr", "fa.vanilla", "fa"]
L = [r"% AUTO-GENERATED by tools/make_cw_tables.py -- do not edit by hand.",
     r"\begin{table}[t]", r"  \centering\tabstyle\footnotesize", r"  \setlength{\tabcolsep}{3pt}",
     r"  \caption{\textbf{Gate ablations on DEV-B} (offline approximation: first marker slot of vanilla continuations). Each gate recalibrated on DEV-A by the CW rule.}",
     r"  \label{tab:cw:abl}",
     r"  \fitwidth{\begin{tabular}{@{}ll r r cc cc@{}}", r"    \toprule",
     r"    & & & & \multicolumn{2}{c}{Hit rate} & \multicolumn{2}{c}{False alarms} \\",
     r"    \cmidrule(lr){5-6} \cmidrule(lr){7-8}",
     r"    Model & Gate & $\tau$ & $\rho_{\mathrm{lo}}$ & van. & gated & van. & gated \\", r"    \midrule"]
n = 0
for mid, name in MODELS:
    rows = []
    for aid, aname in ARMS:
        ks = [f"h5.{mid}.dev.abl.{aid}.{f}" for f in FIELDS]
        if all(k in K for k in ks):
            v = [num(k) for k in ks]
            rows.append(f"{aname} & {v[0]:.3f} & {v[1]:.2f} & {v[2]:.2f} & {v[3]:.2f} & {v[4]:.2f} & {v[5]:.2f}")
    if len(rows) == len(ARMS):
        if n:
            L.append(r"    \addlinespace[0.5mm]\midrule")
        L += [f"    \\oursrow {name} & {rows[0]} \\\\"] + [f"    & {r} \\\\" for r in rows[1:]]
        n += 1
L += [r"    \bottomrule", r"  \end{tabular}}",
      r"\end{table}"]
if n:
    Path("tables/tab_cw_abl_dev.tex").write_text("\n".join(L) + "\n")
print(f"make_cw_tables: {n} models in tab_cw_abl_dev")

# Main CW table (sec:cw:res): paired contrasts against SHAM (same decoder path, never masks; the registered reference
# design) with the contrast against the processor-free vanilla run in grey. Written only when every arm has keys.
def g(k):
    return num(k) if k in K else None
def pm(base, unit):
    e, lo, hi = (g(f"{base}.est.{unit}"), g(f"{base}.lo.{unit}"), g(f"{base}.hi.{unit}"))
    if None in (e, lo, hi):
        return None
    f = lambda x: (r"\ensuremath{-}" if x < 0 else "+") + f"{abs(x):.1f}"
    return f"{f(e)}\\ci{{{f(lo)}}}{{{f(hi)}}}"
MAIN_ARMS = [("nowait", "NoWait"), ("random", "Random (rate-matched)"), ("bf_match", "Budget forcing (matched)"),
             ("bf_loose", "Budget forcing (loose)"), ("cgrs", "CGRS"), ("cw75", r"CW$_{75}$"), ("cw50", r"CW$_{50}$"),
             ("cw", r"\textbf{CW} (ours)")]
rows, missing = [], []
for aid, name in MAIN_ARMS:
    cells = [pm(f"h5.macro.{aid}.acc_vs_sham", "pts"), pm(f"h5.macro.{aid}.tok_vs_sham", "pct"),
             pm(f"h5.macro.{aid}.acc_vs_vanilla", "pts")]
    if None in cells:
        missing.append(aid); continue
    rows.append((r"    \oursrow " if aid == "cw" else "    ") + f"{name} & {cells[0]} & {cells[1]} & \\textcolor{{gray}}{{{cells[2]}}} \\\\")
con = [(f"h5.macro.{c}", n) for c, n in [("S2_cw_minus_nowait", "CW $-$ NoWait (S2)"), ("S3_cw_minus_random", "CW $-$ random (S3)"),
                                       ("S6_cw_minus_bf_match", "CW $-$ budget forcing, matched (S6)")]]
crow = []
for base, n in con:
    e, lo, hi = g(base + ".est"), g(base + ".lo"), g(base + ".hi")
    if None in (e, lo, hi):
        missing.append(base); continue
    f = lambda x: (r"\ensuremath{-}" if x < 0 else "+") + f"{abs(100 * x):.1f}"
    crow.append(f"    {n} & {f(e)}\\ci{{{f(lo)}}}{{{f(hi)}}} & & \\\\")
if not missing:
    T = [r"% AUTO-GENERATED by tools/make_cw_tables.py -- do not edit by hand.", r"\begin{table}[t]", r"  \centering\tabstyle\footnotesize",
         r"  \caption{\textbf{Calibrated Wait against its controls}, macro over models and benchmarks; paired 95\% CIs over problem clusters."
         + ("" if any(k.startswith("h5.olmo3think.cgrs.") for k in K) else " CGRS: three models (OLMo-3-Think running).") + "}",
         r"  \label{tab:cw:main}", r"  \fitwidth{\begin{tabular}{@{}lccc@{}}", r"    \toprule",
         r"    Arm & $\Delta$Acc (pts) & $\Delta$Tokens (\%) & \textcolor{gray}{$\Delta$Acc vs.\ vanilla} \\", r"    \midrule",
         r"    Sham (reference) & 0.0 & 0.0 & \textcolor{gray}{" + (pm("h5.macro.sham.acc_vs_vanilla", "pts") or "") + "} \\\\"]
    T += rows + [r"    \addlinespace[0.5mm]\midrule"] + crow + [r"    \bottomrule", r"  \end{tabular}}", r"\end{table}"]
    Path("tables/tab_cw_main.tex").write_text("\n".join(T) + "\n")
print(f"make_cw_tables: tab_cw_main {'written' if not missing else 'waiting for ' + ', '.join(missing)}")

# DEV-B operating point (S4): hit and false-alarm rates of sham (design-faithful reference), CW, and vanilla (grey),
# on all DEV-B pairs and on the held-out sign-flip family. Rows only for models with every key.
R = []
for mid, name in MODELS:
    ks = [f"h5.{mid}.dev.tau"] + [f"h5.{mid}.dev.{b}.{a}.{m}" for b in ("B_all", "B_signflip") for m in ("hr", "fa") for a in ("sham", "cw", "vanilla")]
    if not all(k in K for k in ks):
        continue
    v = {k: num(k) for k in ks}
    def trio(b, m):
        s_, c_, n_ = (v[f"h5.{mid}.dev.{b}.{a}.{m}"] for a in ("sham", "cw", "vanilla"))
        return f"{s_:.2f} & {c_:.2f} & \\textcolor{{gray}}{{{n_:.2f}}}"
    R.append(f"    {name} & {v[f'h5.{mid}.dev.tau']:.3f} & {trio('B_all','hr')} & {trio('B_signflip','hr')} & {trio('B_all','fa')} \\\\")
if R:
    T = [r"% AUTO-GENERATED by tools/make_cw_tables.py -- do not edit by hand.", r"\begin{table*}[t]", r"  \centering\tabstyle\footnotesize",
         r"  \caption{\textbf{CW does not move the alarm's operating point (S4).} Hit rates on DEV-B and on the held-out sign-flip family, false alarms on clean prefixes; S4 requires false alarms to fall by at least 10 points.}",
         r"  \label{tab:cw:dev}", r"  \fitwidth{\begin{tabular}{@{}lc ccc ccc ccc@{}}", r"    \toprule",
         r"    & & \multicolumn{3}{c}{Hit rate, DEV-B} & \multicolumn{3}{c}{Hit rate, held-out family} & \multicolumn{3}{c}{False alarms (clean prefixes)} \\",
         r"    \cmidrule(lr){3-5} \cmidrule(lr){6-8} \cmidrule(lr){9-11}",
         r"    Model & $\tau$ & sham & CW & \textcolor{gray}{van.} & sham & CW & \textcolor{gray}{van.} & sham & CW & \textcolor{gray}{van.} \\", r"    \midrule"]
    T += R + [r"    \bottomrule", r"  \end{tabular}}", r"\end{table*}"]
    Path("tables/tab_cw_dev.tex").write_text("\n".join(T) + "\n")
print(f"make_cw_tables: {len(R)} models in tab_cw_dev")
