def appendix(tex, label, title):
    """Turn a main table into its appendix companion: new label, short caption pointing to the main table."""
    head, _, _ = tex.partition(r"  \caption{")
    head = head.replace(r"\setlength{\tabcolsep}{1.8pt}", r"\setlength{\tabcolsep}{1.2pt}")
    head = head.replace("\\tabstyle\n", "\\tabstyle\\footnotesize\n", 1)
    return head + r"  \caption{\textbf{%s} Same protocol, columns and conventions as \Cref{%s}.}" % (title, label) + "\n" + \
        r"  \label{%s:app}" % label + "\n" + r"\end{table*}" + "\n"


if __name__ == "__main__":
    root = Path(__file__).resolve().parent.parent / "tables"
    out = {"tab_clines.tex": table1(), "tab_insertion.tex": table2(), "tab_monitors.tex": table3(),
           "tab_app_clines.tex": appendix(table1(TRAJ_APP, main=False), "tab:clines",
                                          "Cline indices for Qwen2.5-1.5B GRPO, the 32B endpoints and gpt-oss-120b."),
           "tab_app_insertion.tex": appendix(table2(TRAJ_APP, main=False), "tab:insertion",
                                             "Insertion effects for Qwen2.5-1.5B GRPO and the 32B endpoints."),
           "tab_app_monitors.tex": appendix(table3(main=False), "tab:monitors", "Monitors on the 32B endpoint pair.")}
    import re
    keys = set(re.findall(r"\\resdef\{([^}]*)\}", (root.parent / "numbers/results.tex").read_text()))

    def no_placeholders(tex):
        """A cell whose key does not exist prints \\na (not run); a .sig marker without key prints nothing; a row left
        with no value is dropped (lead, 2026-10-04: never show a placeholder)."""
        out = []
        for line in tex.split("\n"):
            had = bool(re.search(r"\\(rt|cell|cellsd)\{", line))
            line = re.sub(r"\\sig\{\\rt\{([^}]*)\}\}", lambda m: m.group(0) if m.group(1) in keys else "", line)
            line = re.sub(r"\\rt\{([^}]*\.sig)\}", lambda m: m.group(0) if m.group(1) in keys else "", line)
            line = re.sub(r"\\(rt|cell|cellsd)\{([^}]*)\}", lambda m: m.group(0) if m.group(2) in keys else r"\na", line)
            if had and line.rstrip().endswith("\\\\") and not re.search(r"\\(rt|cell|cellsd)\{", line):
                continue
            out.append(line)
        # a \multirow label whose rows were all dropped is followed directly by a rule: drop it too
        out = [l for i, l in enumerate(out) if not (l.strip().startswith(r"\multirow") and not l.rstrip().endswith("\\\\")
                                                    and i + 1 < len(out) and re.match(r"\s*\\(midrule|bottomrule)", out[i + 1]))]
        return "\n".join(out)

    for name, tex in out.items():
        tex = no_placeholders(tex)
        tex = tex.replace(r"\begin{tabular}", r"\fitwidth{\begin{tabular}").replace(r"\end{tabular}", r"\end{tabular}}")
        (root / name).write_text(tex)
        print("wrote", root / name)
