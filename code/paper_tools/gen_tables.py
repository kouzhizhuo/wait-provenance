def t3_row(name, m, sb, stb, sl, stl):
    c = [r"\rt{mon.%s.%s.%s_tstep_labels}" % (sl, stl, m),
         r"\cellsd{mon.%s.%s.%s_tstep_auroc}" % (sb, stb, m), r"\cellsd{mon.%s.%s.%s_tstep_auroc}" % (sl, stl, m),
         r"\rt{mon.%s.trend.%s_tstep_dauroc}\sig{\rt{mon.%s.trend.%s_tstep_dauroc.sig}}" % (sl, m, sl, m),
         r"\cellsd{mon.%s.%s.%s_tstep_ece}" % (sl, stl, m),
         r"\cellsd{mon.%s.%s.%s_tstepnat_auroc}" % (sb, stb, m), r"\cellsd{mon.%s.%s.%s_tstepnat_auroc}" % (sl, stl, m),
         r"\rt{mon.%s.trend.%s_tstepnat_dauroc}\sig{\rt{mon.%s.trend.%s_tstepnat_dauroc.sig}}" % (sl, m, sl, m)]
    return "    " + name + " & " + " & ".join(c[:5]) + " & & " + " & ".join(c[5:]) + r" \\"


